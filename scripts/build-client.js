#!/usr/bin/env node
/**
 * Build the hand-bundled browser client (no bundler).
 * Usage:  node auto-direction/scripts/build-client.js [--check]
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const root = join(here, '..')
const srcDir = join(root, 'src', 'client')
const outPath = join(root, 'lib', 'client.js')
const PLUGIN_ID = 'dsh-client-ui-auto-direction'

function read(name) { return readFileSync(join(srcDir, name), 'utf8') }

function inline(name) {
  const lines = read(name).split('\n')
  const out = []
  for (const line of lines) {
    if (/^\s*import\s/.test(line)) continue
    if (/^\s*export\s*\{[^}]*\}\s*;?\s*$/.test(line)) continue
    const m = line.match(/^(\s*)export\s+(?=(?:async\s+)?(?:function|const|let|var|class)\b)/)
    if (m !== null) { out.push(line.replace(/^(\s*)export\s+/, '$1')); continue }
    out.push(line)
  }
  return out.join('\n')
}

function build() {
  const guard = inline('apply-guard.js')
  const entry = inline('index.js')
  return `window.__ModuleLoader__.load({
  id: '${PLUGIN_ID}',
  factory: (require) => {
    var module = { exports: {} }
    var exports = module.exports
    let react = require('react')
    // Generated by scripts/build-client.js — do not hand-edit. Edit src/client/*.js and rebuild.
${guard}

${entry}
    exports.apply = apply
    exports.inject = inject
    return exports
  },
})
`
}

const check = process.argv.includes('--check')
const built = build()
if (check) {
  const current = readFileSync(outPath, 'utf8')
  if (current !== built) { console.error('lib/client.js is stale: run build'); process.exit(1) }
  console.log('lib/client.js is up to date')
} else {
  writeFileSync(outPath, built)
  console.log(`wrote ${outPath} (${built.length} bytes)`)
}
